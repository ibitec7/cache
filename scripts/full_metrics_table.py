"""Full per-cluster metric table for the appendix."""
from __future__ import annotations

from mrc.analysis import load_metrics
from mrc.config import REPO

TEX = REPO / "report" / "tables" / "full_metrics.tex"
CLUSTERS = ("cluster45", "cluster26", "cluster10")
MODELS = (("gbdt", "hazard"), ("km", "Kaplan-Meier"), ("hitcount", "hit-count"))


def main() -> None:
    lines = ["% generated by scripts/full_metrics_table.py; do not edit",
             "\\begin{table}[t]", "\\centering", "\\scriptsize",
             "\\caption{Every metric on every trace and estimator, test block, 24-point "
             "grid (12 on cluster10). ABC is the log-normalised area between curves.}",
             "\\label{tab:full-metrics}",
             "\\begin{tabular}{@{}l l r r r r r@{}}", "\\toprule",
             "Trace & Estimator & MAE & MAX & bias & MRE & ABC \\\\", "\\midrule"]
    for cluster in CLUSTERS:
        metrics = load_metrics(cluster)["metrics"]["test"]
        for key, label in MODELS:
            m = metrics[key]
            lines.append(f"{cluster} & {label} & {m['mae']:.5f} & {m['max_abs']:.5f} & "
                         f"{m['bias']:+.5f} & {m['mre']:.4f} & {m['abc']:.4f} \\\\")
        lines.append("\\midrule")
    lines[-1] = "\\bottomrule"
    lines += ["\\end{tabular}", "\\end{table}"]
    TEX.write_text("\n".join(lines) + "\n")
    print("wrote", TEX)


if __name__ == "__main__":
    main()
