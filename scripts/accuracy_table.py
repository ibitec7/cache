"""One compact accuracy table: rows are estimators, columns are traces."""
from __future__ import annotations

from mrc.analysis import load_metrics
from mrc.config import REPO

TEX = REPO / "report" / "tables" / "accuracy.tex"
CLUSTERS = ("cluster45", "cluster26", "cluster10")
MODELS = (("gbdt", "Hazard GBDT"), ("km", "Kaplan-Meier"), ("hitcount", "Hit-count regression"))


def main() -> None:
    lines = ["% generated by scripts/accuracy_table.py; do not edit",
             "\\begin{table}[t]", "\\centering", "\\footnotesize",
             "\\caption{Test-block error over the 24-point capacity grid. Each cell is "
             "MAE over MAX; lower is better. The same three traces, split, grid and "
             "scoring code for every row.}",
             "\\label{tab:accuracy}",
             "\\begin{tabular}{@{}l r r r@{}}", "\\toprule",
             "Estimator & cluster45 & cluster26 & cluster10 \\\\", "\\midrule"]
    for key, label in MODELS:
        cells = []
        for cluster in CLUSTERS:
            m = load_metrics(cluster)["metrics"]["test"][key]
            cells.append(f"{m['mae']:.5f} / {m['max_abs']:.5f}")
        lines.append(f"{label} & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    TEX.write_text("\n".join(lines) + "\n")
    print("wrote", TEX)


if __name__ == "__main__":
    main()
