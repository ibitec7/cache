"""Is the measured curve error above the sampling noise of the truth itself?

The truth curve on a block is an empirical survival function over n eligible
requests, so at capacity C it carries binomial standard error sqrt(p(1-p)/n). An
error below that standard error is not a smaller error: it is the same error,
measured to the precision the block allows. This prints the per-capacity standard
error beside each model's error, writes artifacts/tables/noise_floor.json, and
writes the report table.

Caveat stated with the number: requests are not independent, so the true standard
error is larger than binomial, which makes this a lower bound on the floor.

Usage: env -u PYTHONPATH uv run python scripts/noise_floor.py [cluster ...]
"""
from __future__ import annotations

import json
import sys

import numpy as np

from mrc.analysis import reported_clusters
from mrc.config import REPO
from mrc.data.labels import load_labels
from mrc.pipeline import TABLE_DIR, block_masks, labels_path

TEX = REPO / "report" / "tables" / "noise_floor.tex"
MODELS = (("gbdt", "Hazard GBDT"), ("km", "Kaplan-Meier"), ("hitcount", "Hit-count"))


def floor_for(cluster: str) -> dict:
    labels = load_labels(labels_path(cluster))
    eligible = np.asarray(labels["eligible"], dtype=bool)
    _, _, test = block_masks(int(eligible.shape[0]))
    n = int((test & eligible).sum())

    metrics = json.loads((TABLE_DIR / f"{cluster}_metrics.json").read_text())
    curves = np.load(TABLE_DIR / f"{cluster}_curves.npz")
    truth = np.asarray(curves["truth_test"])
    se = np.sqrt(np.clip(truth * (1.0 - truth), 0.0, None) / n)
    out = {"cluster": cluster, "n_eligible_test": n, "se_median": float(np.median(se)),
           "se_max": float(se.max()), "models": {}}
    for name in ("gbdt", "km", "hitcount"):
        mae = float(metrics["metrics"]["test"][name]["mae"])
        per_cap = np.abs(np.asarray(curves[f"{name}_test"]) - truth)
        out["models"][name] = {
            "mae": mae,
            "mae_over_se_median": mae / out["se_median"],
            "caps_below_1se": int((per_cap <= se).sum()),
            "caps": int(per_cap.size),
        }
    return out


def write_table(rows: list[dict]) -> None:
    lines = ["% generated by scripts/noise_floor.py; do not edit",
             "\\begin{table}[t]", "\\centering", "\\footnotesize",
             ("\\caption{Model error against the sampling noise of the truth curve. "
              "$n$ is the number of eligible requests in the test block and $\\mathrm{SE}$ "
              "the median binomial standard error of the empirical survival curve over "
              "its capacities, $\\sqrt{p(1-p)/n}$, a lower bound on the true error of "
              "the truth because requests are serially dependent. A ratio below one "
              "means the model is inside the resolution of the block.}"),
             "\\label{tab:noise}",
             "\\begin{tabular}{@{}l r r l r r@{}}", "\\toprule",
             ("Trace & $n$ & $\\mathrm{SE}$ & Estimator & MAE/$\\mathrm{SE}$ "
              "& within $1\\,\\mathrm{SE}$ \\\\"), "\\midrule"]
    for row in rows:
        for i, (key, label) in enumerate(MODELS):
            m = row["models"][key]
            head = (f"{row['cluster']} & \\num{{{row['n_eligible_test']}}} & "
                    f"\\num{{{row['se_median']:.2e}}} & {label}") if i == 0 else f" & & & {label}"
            lines.append(f"{head} & {m['mae_over_se_median']:.2f} & "
                         f"{m['caps_below_1se']}/{m['caps']} \\\\")
        if row is not rows[-1]:
            lines.append("\\midrule")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    TEX.write_text("\n".join(lines) + "\n")
    print("wrote", TEX)


def main() -> None:
    clusters = sys.argv[1:] or list(reported_clusters())
    rows = [floor_for(c) for c in clusters]
    for r in rows:
        print(f"\n{r['cluster']}: n_eligible_test={r['n_eligible_test']:,} "
              f"truth SE median={r['se_median']:.2e} max={r['se_max']:.2e}")
        for name, m in r["models"].items():
            print(f"  {name:9s} MAE={m['mae']:.5f}  MAE/SE={m['mae_over_se_median']:6.2f}  "
                  f"capacities within 1 SE of truth: {m['caps_below_1se']}/{m['caps']}")
    (TABLE_DIR / "noise_floor.json").write_text(json.dumps(rows, indent=2) + "\n")
    write_table(rows)


if __name__ == "__main__":
    main()
