"""Compact provisioning table: capacity ratio model/truth."""
from __future__ import annotations

import math

from mrc.analysis import load_metrics, reported_clusters
from mrc.config import REPO

TEX = REPO / "report" / "tables" / "provisioning.tex"
MODELS = (("gbdt", "Hazard GBDT"), ("km", "Kaplan-Meier"))


def main() -> None:
    clusters = reported_clusters()
    lines = ["% generated by scripts/provisioning_table.py; do not edit",
             "\\begin{table}[t]", "\\centering", "\\footnotesize",
             ("\\caption{Capacity ratio, model over truth, for a target hit ratio stated as a "
              "fraction of the ceiling $1-p_c$. Below one under-provisions.}"),
             "\\label{tab:provisioning}",
             "\\begin{tabular}{@{}l l r r r@{}}", "\\toprule",
             "Trace & Model & 60\\% & 80\\% & 95\\% \\\\", "\\midrule"]
    for cluster in clusters:
        payload = load_metrics(cluster)
        for key, label in MODELS:
            cells = []
            for entry in payload["metrics"]["provisioning"][key]:
                ratio = entry["ratio"]
                cells.append("n/a" if math.isnan(ratio) else f"{ratio:.3f}")
            lines.append(f"{cluster} & {label} & " + " & ".join(cells) + " \\\\")
        if cluster != clusters[-1]:
            lines.append("\\midrule")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    TEX.write_text("\n".join(lines) + "\n")
    print("wrote", TEX, "rows:", clusters)


if __name__ == "__main__":
    main()
