"""Generated error tables: markdown for the wiki, booktabs for the report.

A row is a model metric dict from `artifacts/tables/<cluster>_metrics.json`, whose
keys come from `mrc.eval.metrics.curve_metrics`: `mae`, `max_abs`, `bias`, `mre`,
`mre_n`, `abc`, `n`. The columns are fixed here so the wiki and the report cannot
drift apart, and an absent value prints `n/a` rather than a zero that reads as a
measurement.

`report/tables/*.tex` is generated: `booktabs` writes it only when given a path, and
the first line says so, so a hand edit is visible in a diff.
"""
from __future__ import annotations

from collections.abc import Mapping
from pathlib import Path

COLUMNS = ("model", "MAE", "MAX", "bias", "MRE", "n")
"""Fixed table columns; `model` is the row label, the rest are metric json values."""

DIGITS = 4
MISSING = "n/a"

MetricRow = Mapping[str, float | None]


def _fmt(value: float | None) -> str:
    return MISSING if value is None else f"{float(value):.{DIGITS}f}"


def _fmt_count(value: float | None) -> str:
    return MISSING if value is None else str(int(value))


def _rows(metrics: Mapping[str, MetricRow]) -> list[list[str]]:
    """One cell list per model, in the order the metric dict carries."""
    if not metrics:
        raise ValueError("metrics is empty")
    return [
        [
            model,
            _fmt(row.get("mae")),
            _fmt(row.get("max_abs")),
            _fmt(row.get("bias")),
            _fmt(row.get("mre")),
            _fmt_count(row.get("n")),
        ]
        for model, row in metrics.items()
    ]


def metrics_table(cluster: str, metrics: Mapping[str, MetricRow]) -> str:
    """Markdown table, one row per model, followed by its provenance line.

    The header row is the first character of the returned string, so the table can
    be embedded under any heading; the cluster name and the json it came from are
    named on the line below the table.
    """
    rows = _rows(metrics)
    lines = [
        "| " + " | ".join(COLUMNS) + " |",
        "|" + "|".join(["---"] * len(COLUMNS)) + "|",
    ]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    lines += ["", f"*{cluster}: `artifacts/tables/{cluster}_metrics.json`*"]
    return "\n".join(lines) + "\n"


def booktabs(
    metrics: Mapping[str, MetricRow],
    caption: str,
    label: str,
    path: str | Path | None = None,
) -> str:
    """LaTeX booktabs table; write `path` when given and always return the string.

    `caption` and `label` are passed through unescaped, so maths in the caption is
    written by the caller (`$C$`, `$b_{M-1}$`).
    """
    rows = _rows(metrics)
    aligns = "l" + "r" * (len(COLUMNS) - 1)
    lines = [
        "% generated by mrc.report_tables.booktabs; do not edit",
        "\\begin{table}[t]",
        "\\centering",
        f"\\caption{{{caption}}}",
        f"\\label{{{label}}}",
        f"\\begin{{tabular}}{{{aligns}}}",
        "\\toprule",
        " & ".join(COLUMNS) + " \\\\",
        "\\midrule",
    ]
    lines += [" & ".join(row) + " \\\\" for row in rows]
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    tex = "\n".join(lines) + "\n"
    if path is not None:
        out = Path(path)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(tex)
    return tex
